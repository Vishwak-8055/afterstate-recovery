from __future__ import annotations

import contextlib
import hashlib
import os
import re
import uuid
from collections.abc import Iterable
from pathlib import Path

from afterstate.storage.base import ObjectNotFound, ObjectTooLarge, StorageError, StoredObject

_KEY = re.compile(r"^[a-z0-9][a-z0-9_\-./]{0,250}$")


class UploadHandle:
    """Incremental, size-limited, hashed write that only becomes visible on commit()."""

    def __init__(self, tmp: Path, target: Path, key: str, max_bytes: int) -> None:
        self._tmp, self._target, self.key, self._max = tmp, target, key, max_bytes
        self._digest = hashlib.sha256()
        self.size = 0
        self._fh = os.fdopen(os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "wb")

    def write(self, chunk: bytes) -> None:
        self.size += len(chunk)
        if self.size > self._max:
            raise ObjectTooLarge(f"upload exceeds the {self._max} byte limit")
        self._digest.update(chunk)
        self._fh.write(chunk)

    def commit(self) -> StoredObject:
        self._fh.flush()
        os.fsync(self._fh.fileno())
        self._fh.close()
        self._target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        os.replace(self._tmp, self._target)
        return StoredObject(self.key, self.size, self._digest.hexdigest())

    def abort(self) -> None:
        with contextlib.suppress(Exception):
            self._fh.close()
        self._tmp.unlink(missing_ok=True)


class LocalArtifactStorage:
    """Stores objects under a root directory. Keys are generated by the platform, never taken from
    user input, and are additionally validated so they cannot escape the root."""

    def __init__(self, root: Path) -> None:
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True, mode=0o700)
        (self.root / ".tmp").mkdir(exist_ok=True, mode=0o700)

    def _resolve(self, key: str) -> Path:
        if not _KEY.match(key) or ".." in key.split("/") or "//" in key:
            raise StorageError(f"invalid storage key: {key!r}")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise StorageError("storage key escapes the storage root")
        return path

    def write_stream(self, key: str, chunks: Iterable[bytes], *, max_bytes: int) -> StoredObject:
        target = self._resolve(key)
        tmp = self.root / ".tmp" / uuid.uuid4().hex
        digest = hashlib.sha256()
        size = 0
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        try:
            with os.fdopen(fd, "wb") as fh:
                for chunk in chunks:
                    size += len(chunk)
                    if size > max_bytes:
                        raise ObjectTooLarge(f"object exceeds the {max_bytes} byte limit")
                    digest.update(chunk)
                    fh.write(chunk)
                fh.flush()
                os.fsync(fh.fileno())
            target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            os.replace(tmp, target)
        except BaseException:
            tmp.unlink(missing_ok=True)
            raise
        return StoredObject(key=key, size_bytes=size, sha256=digest.hexdigest())

    def open_upload(self, key: str, *, max_bytes: int) -> UploadHandle:
        return UploadHandle(self.root / ".tmp" / uuid.uuid4().hex, self._resolve(key), key, max_bytes)

    def write_bytes(self, key: str, data: bytes) -> StoredObject:
        return self.write_stream(key, [data], max_bytes=max(len(data), 1))

    def read_bytes(self, key: str) -> bytes:
        path = self._resolve(key)
        try:
            return path.read_bytes()
        except FileNotFoundError as exc:
            raise ObjectNotFound(key) from exc

    def resolve(self, key: str) -> Path:
        return self._resolve(key)

    def path_for(self, key: str) -> Path:
        path = self._resolve(key)
        if not path.is_file():
            raise ObjectNotFound(key)
        return path

    def exists(self, key: str) -> bool:
        return self._resolve(key).is_file()

    def size(self, key: str) -> int:
        return self.path_for(key).stat().st_size

    def delete(self, key: str) -> None:
        self._resolve(key).unlink(missing_ok=True)


def new_artifact_key(workspace_id: uuid.UUID) -> str:
    return f"ws/{workspace_id.hex}/artifacts/{uuid.uuid4().hex}"


def new_evidence_key(run_id: uuid.UUID, name: str) -> str:
    safe = re.sub(r"[^a-z0-9_.-]", "-", name.lower())
    return f"runs/{run_id.hex}/{safe}"
