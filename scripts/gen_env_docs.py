"""Generate docs/environment.md from the Settings model so the reference can never drift from the code."""
from pathlib import Path

from afterstate.config import Settings

DOCS = {
    "environment": "development, test or production. Production refuses unsafe settings (insecure cookies, default DB credentials).",
    "database_url": "SQLAlchemy URL of the platform metadata database (PostgreSQL).",
    "artifact_dir": "Where backups and run evidence are stored. Must be shared by API and worker.",
    "scratch_dir": "Where disposable restore environments are created. Keep the path short (unix socket limit) and give it plenty of disk.",
    "max_artifact_bytes": "Largest backup accepted by upload and restore.",
    "max_json_body_bytes": "Largest JSON request body.",
    "session_ttl_seconds": "Session lifetime.",
    "session_cookie_secure": "Mark cookies Secure. Required in production.",
    "allow_registration": "Allow self-service sign-up.",
    "allowed_origins": "JSON list of public origins allowed for CSRF origin checks and CORS.",
    "rate_limit_auth_per_minute": "Sign-in and registration attempts per client IP per minute (per API process).",
    "rate_limit_api_per_minute": "Requests per client IP per minute (per API process).",
    "pg_bin_dir": "Directory with PostgreSQL binaries; auto-detected when unset.",
    "max_environment_bytes": "Disk cap per restore environment; the restore is killed if exceeded.",
    "default_restore_timeout_seconds": "Default restore timeout for new projects.",
    "default_validation_timeout_seconds": "Default validation budget for new projects.",
    "environment_shared_buffers_mb": "shared_buffers of each disposable cluster.",
    "max_log_events_per_run": "Log events kept per run before truncation (full transcript stays in the evidence file).",
    "worker_poll_seconds": "Queue polling interval.",
    "worker_lease_seconds": "Run lease; a run whose lease expires is recovered by the reaper.",
    "worker_heartbeat_seconds": "Lease heartbeat interval.",
    "scheduler_tick_seconds": "Scheduler pass interval.",
    "cleanup_retry_delay_seconds": "Delay before retrying a failed cleanup.",
    "max_concurrent_runs_default": "Default per-workspace concurrency for new workspaces.",
    "lab_enabled": "Enable the Recovery Lab.",
    "fault_injection_enabled": "Honour faults on Recovery Lab runs (never on other runs).",
    "webhook_allow_private_hosts": "Allow webhooks to private addresses. Development only; refused in production.",
    "log_level": "Log level.",
    "log_json": "Structured JSON logs.",
}
rows = ["| Variable | Type | Default | Description |", "|---|---|---|---|"]
for name, field in Settings.model_fields.items():
    default = field.default if field.default is not None else ("[]" if name == "allowed_origins" else "auto")
    if name == "database_url":
        default = "postgresql+psycopg://afterstate:afterstate@localhost:5432/afterstate (rejected in production)"
    rows.append(f"| `AFTERSTATE_{name.upper()}` | `{getattr(field.annotation, '__name__', str(field.annotation))}` | `{default}` | {DOCS.get(name, '')} |")
Path(__file__).resolve().parents[1].joinpath("docs/environment.md").write_text(
    "# Environment variables\n\nGenerated by `scripts/gen_env_docs.py` from the `Settings` model. Every setting is prefixed `AFTERSTATE_`.\n\n" + "\n".join(rows) + "\n"
)
print("wrote docs/environment.md")
